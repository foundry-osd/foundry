using Foundry.Core.Models.Configuration;
using Foundry.Core.Models.Configuration.Deploy;
using Foundry.Telemetry;

namespace Foundry.Connect.Configuration;

/// <summary>
/// The Connect view of <c>foundry.winpe.config.json</c>: the shared root sections of <see cref="FoundryWinPeConfigurationDocument"/>
/// and the properties of its <c>connect</c> section, flattened by
/// <see cref="Foundry.Core.Services.Configuration.WinPeConfigurationReader.ReadModeView"/>.
/// </summary>
public sealed record FoundryConnectConfigurationDocument
{
    /// <summary>Gets the schema version of the WinPE runtime configuration.</summary>
    public int SchemaVersion { get; init; } = ConfigurationSchemaVersions.WinPeCurrent;

    /// <summary>Gets the OSD release that authored this media, when recorded.</summary>
    public string? AuthoringVersion { get; init; }

    /// <summary>Gets media capability flags generated by the app.</summary>
    public ConnectNetworkCapabilitiesSettings Capabilities { get; init; } = new();

    /// <summary>Gets the network profile roaming shared with Deploy.</summary>
    public WinPeNetworkSettings Network { get; init; } = new();

    /// <summary>Gets wired 802.1X provisioning settings.</summary>
    public ConnectDot1xSettings Dot1x { get; init; } = new();

    /// <summary>Gets Wi-Fi provisioning settings.</summary>
    public ConnectWifiSettings Wifi { get; init; } = new();

    /// <summary>Gets the telemetry policy shared by the guardian, Connect and Deploy.</summary>
    public TelemetrySettings Telemetry { get; init; } = new();

    /// <summary>
    /// Gets the deployment password protection block shared with Deploy. It is always present; the media can be unlocked only
    /// when it is enabled and carries the password-wrapped deployment key.
    /// </summary>
    public DeployProtectionSettings Protection { get; init; } = new();
}
